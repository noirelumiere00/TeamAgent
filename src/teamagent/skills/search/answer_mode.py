"""検索の質問を「事実確認 / 一覧 / 洞察」に分ける（決定的・LLM 不使用）。

案件検索 v3 PR 1（2026-10-01）。v2d の system prompt は「単純要約はせず、必ず抽象化して返す」
を全質問に強制しており、「最新の提案書どこ？」「撮影日いつ？」のような事実の質問にも
パターンと推奨アクションが返っていた（見直し報告の R2・幹部の「アウトプットが違う」の推定原因）。
v3 では質問の種類をここで決め、user message に回答モードとして渡す。

判定の方針（誤りの向きを決めておく）:
- 洞察の合図（傾向・パターン・どう攻める・刺さる 等）が**明示されたときだけ** insight。
  合図が無ければ事実確認か一覧に倒す。事実の質問に提言を混ぜる誤りの方が、
  洞察の質問に事実だけ返す誤りより害が大きい（後者は利用者が聞き直せる）。
- 一覧の合図（一覧・リスト・全部・何件 等）があり洞察の合図が無ければ list。
- それ以外は fact。
"""

from __future__ import annotations

import re
from typing import Literal

AnswerMode = Literal["fact", "list", "insight"]

# 洞察（パターン抽出・打ち手）を明示的に求める言い回し。
_INSIGHT_RE = re.compile(
    r"傾向|パターン|共通点|勝ち筋|勝ちパターン|示唆|インサイト|戦略|打ち手|攻め方|攻めれば|"
    r"どう(?:攻め|動け|提案す|切り返|進め|すれば|したら)|刺さ(?:る|った|りやすい)|"
    r"切り返し|改善点|アイデア|ヒント|学び|教訓|コツ|ポイントを?(?:教えて|まとめて)|"
    r"なぜ(?:受注|失注|刺さ|決ま)"
)

# 一覧・列挙を求める言い回し。
_LIST_RE = re.compile(r"一覧|リスト|全部|すべて|全て|何件|いくつ|洗い出|列挙|まとめて(?:出|見せ)")


def classify_answer_mode(query: str) -> AnswerMode:
    """質問文から回答モードを決める。"""
    text = query or ""
    if _INSIGHT_RE.search(text):
        return "insight"
    if _LIST_RE.search(text):
        return "list"
    return "fact"


# user message に足す回答モードの指示（system prompt v3 の各節と対応する）。
MODE_INSTRUCTIONS: dict[AnswerMode, str] = {
    "fact": (
        "# 回答モード: 事実確認\n"
        "質問に対する事実だけを 1 文目で答える。根拠にした資料名（と日付があれば日付）を添える。"
        "傾向・推奨アクション・提言は書かない。資料に無い事実は「資料に記載がありません」と書く。"
    ),
    "list": (
        "# 回答モード: 一覧\n"
        "該当する資料・案件を 1 行ずつ並べる（資料名と日付）。並べ終えたら終わる。"
        "傾向・推奨アクション・提言は書かない。漏れがありうるときは「見つかった範囲では」と断る。"
    ),
    "insight": (
        "# 回答モード: 洞察\n資料に共通するパターンと打ち手まで踏み込む。根拠にした資料名を添える。"
    ),
}
