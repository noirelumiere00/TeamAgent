"""業種（industry）の正準語彙。**書き込み側と読み出し側の唯一の真実源**。

2026-08-28 の実測で、業種語彙が 3 層に分かれて互いに一致していないことが判明した:

  書き込み  ingest/classify.py     「例: 食品 / 化粧品 / … 等」＝ **開いた**語彙（LLM が自由に生成）
  読み出し① search/knowledge_query.py  11 語の固定キーワード表
  読み出し② skills/router.py           13 語の固定リスト（**「食品」自体が無い**）

実害: 営業が「ヨーグルト 乳製品」で検索したところ ``filter_industry=null`` になり、
返った 10 件のうち **9 件が「ヨーグルト」も「乳製品」も 1 文字も含まない**
（玩具・鉄道・金融・電機の提案書）状態で回答が生成された。

さらに書き込み側が開いているため、**同一クライアントが ``旅行`` と ``旅行・観光`` の
2 通りに揺れて**保存されていた（実測）。

本モジュールはその 3 層を 1 本に束ねる。

## 設計の要点

- ``CANONICAL_INDUSTRIES`` は **閉じた**リスト。書き込み側の LLM もここから選ぶ
- ``ALIASES`` は **保存済みデータの表記ゆれ**を正準値へ寄せるためだけのもの。
  「ヨーグルト → 食品」のような **商材語 → 業種**の対応をここに足してはいけない。
  それはキーワード表を厚くするのと同じで、次は「グラノーラ」で同じ事故が起きる。
  商材語の解釈は LLM ルーター（``INDUSTRY_PROMPT_LIST`` を渡す）の仕事である
- ``normalize_industry`` は未知値を「その他」へ潰さず **None** を返す。
  ``filter_industry`` は soft フィルタ（``industry = 値 OR industry IS NULL``）なので、
  未知値を勝手に正準値へ寄せると**本来ヒットすべき文書を取りこぼす**側に倒れる
- ``INDUSTRY_PROMPT_LIST`` は ``CANONICAL_INDUSTRIES`` から機械生成する。
  プロンプト側にリストを手書きすると二重管理になり、また 3 層に分かれる

## 既存データを再分類しない

ingest は平日毎日 949 件を全件再分類しており、ここが AWS 費用の主因である。
タクソノミ変更のために再分類バッチを走らせてはいけない。
**読み出し時に ``normalize_industry`` を通す**ことで、``旅行・観光`` として保存済みの
文書が ``旅行`` のクエリでヒットするようにしてある。
"""

