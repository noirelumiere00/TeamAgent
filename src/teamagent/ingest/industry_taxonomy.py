def match_industry_keyword(query: str | None) -> str | None:
    """クエリに業界を名指しする語があれば正準値を返す。無ければ None。

    **これは高速路であって本命ではない。** 商材語（ヨーグルト等）はここでは拾えず、
    None が返る。呼び出し側は None のときに LLM ルーターへ委ねること。
    """
    if not query:
        return None
    for industry, keywords in _INDUSTRY_KEYWORDS.items():
        if any(kw in query for kw in keywords):
            return industry
    return None


def is_canonical_industry(value: str | None) -> bool:
    """``value`` が正準値そのものか。"""
    return value in CANONICAL_INDUSTRIES


def normalize_industry(value: str | None) -> str | None:
    """保存値・クエリ由来の業種文字列を正準値へ正規化する。

    - 正準値ならそのまま返す
    - ``ALIASES`` に載っていれば正準値へ寄せる
    - それ以外（未知値・空・None）は **None** を返す

    🔴 未知値を ``OTHER_INDUSTRY`` へ潰さないのは意図的である。
    ``filter_industry`` は soft フィルタ（``industry = 値 OR industry IS NULL``）なので、
    未知値を「その他」に寄せると、本来 soft に通るはずの文書が
    「その他 ≠ 食品」として**除外される**側に倒れる。None（＝業種を主張しない）が安全側。
    """
    if not value:
        return None
    trimmed = value.strip()
    if not trimmed:
        return None
    if trimmed in CANONICAL_INDUSTRIES:
        return trimmed
    return _ALIASES.get(trimmed)
